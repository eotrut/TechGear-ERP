import { writeFileSync } from "node:fs";
import type { Role } from "@prisma/client";

import { scopeFor } from "../src/lib/rbac/can";
import { MATRIX, PERMISSION_GROUPS, PERMISSIONS } from "../src/lib/rbac/matrix";
import { ROUTE_RULES } from "../src/lib/rbac/routes";

/**
 * Generates docs/permissions.md from src/lib/rbac/matrix.ts.
 *
 * The documentation is generated rather than written so it cannot drift from
 * the code that actually enforces access. Run `npm run gen:permissions` after
 * changing the matrix.
 */

const ROLES: Role[] = ["ADMIN", "MANAGER", "SALES", "WAREHOUSE"];

function cell(role: Role, permission: (typeof PERMISSIONS)[number]): string {
  const access = scopeFor(role, permission);
  if (access === "all") return "Y";
  if (access === "own") return "own";
  return "-";
}

const lines: string[] = [];

lines.push("# Permission matrix");
lines.push("");
lines.push("> Generated by `npm run gen:permissions` from `src/lib/rbac/matrix.ts`.");
lines.push("> Do not edit by hand: the matrix module is the source of truth and this file");
lines.push("> is regenerated from it, so any edit here would be silently overwritten.");
lines.push("");
lines.push("`Y` full access, `own` limited to records the user owns or created, `-` denied.");
lines.push("");
lines.push("Enforced at three layers:");
lines.push("");
lines.push(
  "1. `src/middleware.ts` gates navigation against the JWT (fast, and stale by up to the token lifetime).",
);
lines.push("2. `requirePermission()` in every protected page, re-reading the live user record.");
lines.push(
  "3. `authorizeAction()` / `authorizeRecord()` in every server action and route handler.",
);
lines.push("");
lines.push("The UI hides what a role cannot do, but hiding is never the control.");
lines.push("");

for (const group of PERMISSION_GROUPS) {
  lines.push(`## ${group.label}`);
  lines.push("");
  lines.push(`| Permission | ${ROLES.join(" | ")} |`);
  lines.push(`|---|${ROLES.map(() => ":--:").join("|")}|`);
  for (const permission of group.permissions) {
    lines.push(
      `| \`${permission}\` | ${ROLES.map((role) => cell(role, permission)).join(" | ")} |`,
    );
  }
  lines.push("");
}

lines.push("## Route gate");
lines.push("");
lines.push("The permission each route requires, checked by middleware before the page renders.");
lines.push("Rules are evaluated most specific first.");
lines.push("");
lines.push(`| Route | Permission | ${ROLES.join(" | ")} |`);
lines.push(`|---|---|${ROLES.map(() => ":--:").join("|")}|`);
for (const rule of ROUTE_RULES) {
  const cells = ROLES.map((role) => (scopeFor(role, rule.permission) ? "Y" : "-")).join(" | ");
  lines.push(`| \`${rule.prefix}\` | \`${rule.permission}\` | ${cells} |`);
}
lines.push("");

lines.push("## Totals");
lines.push("");
lines.push(`| Role | Permissions held | of ${PERMISSIONS.length} |`);
lines.push("|---|--:|--:|");
for (const role of ROLES) {
  const held = PERMISSIONS.filter((permission) => MATRIX[permission][role] !== undefined).length;
  const percent = Math.round((held / PERMISSIONS.length) * 100);
  lines.push(`| ${role} | ${held} | ${percent}% |`);
}
lines.push("");

writeFileSync("docs/permissions.md", `${lines.join("\n")}`, "utf8");
console.log(
  `docs/permissions.md written: ${PERMISSIONS.length} permissions, ${ROUTE_RULES.length} route rules.`,
);
